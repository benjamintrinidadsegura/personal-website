function buildLocaleCopy(values: readonly string[]): Record<LifeVisionUiSourceKey, string> {
  return Object.fromEntries(LIFE_VISION_UI_SOURCE_KEYS.map((source, index) => [source, values[index]])) as Record<LifeVisionUiSourceKey, string>;
}

export const lifeVisionUiVisionCopy: Record<LifeVisionUiLocale, Record<LifeVisionUiSourceKey, string>> = {
  es: buildLocaleCopy(translations.es),
  tr: buildLocaleCopy(translations.tr),
  pl: buildLocaleCopy(translations.pl),
  el: buildLocaleCopy(translations.el),
  ru: buildLocaleCopy(translations.ru),
};

const templateTokenPattern = /\{\{[^{}]+\}\}|\$\{[^{}]+\}|\{[^{}]+\}|%[sdif]/g;

function templateTokens(value: string): readonly string[] {
  return value.match(templateTokenPattern) ?? [];
}

export function assertLifeVisionUiVisionCopyCompleteness(): void {
  const sources = new Set(LIFE_VISION_UI_SOURCE_KEYS);
  if (sources.size !== LIFE_VISION_UI_SOURCE_KEYS.length) {
    throw new Error("Life Vision UI source strings must be unique.");
  }

  for (const [locale, copy] of Object.entries(lifeVisionUiVisionCopy)) {
    const keys = Object.keys(copy);
    if (keys.length !== sources.size || keys.some((key) => !sources.has(key as LifeVisionUiSourceKey))) {
      throw new Error(`Life Vision UI copy is incomplete for ${locale}.`);
    }

    for (const source of LIFE_VISION_UI_SOURCE_KEYS) {
      const translated = copy[source];
      if (typeof translated !== "string" || !translated.trim()) {
        throw new Error(`Life Vision UI copy is blank for ${locale}: ${source}`);
      }
      if (templateTokens(source).join("\u0000") !== templateTokens(translated).join("\u0000")) {
        throw new Error(`Life Vision UI template tokens differ for ${locale}: ${source}`);
      }
    }
  }
}

assertLifeVisionUiVisionCopyCompleteness();
